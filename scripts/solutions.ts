// npm run solutions          → writes docs/solutions.md (the instructor answer key)
// npm run solutions -- --check → fails if docs/solutions.md is out of date (used in CI)
//
// Codeweald has no teacher features in the app (owner decision Q13). Instructors prepare for
// students' questions with this generated document instead.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { BossQuestFile, NormalQuestFile, PhaseFile, QuestFile } from '../src/content/schema';
import { loadContent, solutionCode, type Body } from './lib/content';
import { reportProblems } from './lib/report';

const OUT = join(import.meta.dirname, '..', 'docs', 'solutions.md');

const fence = (code: string, lang = 'python') => `\`\`\`${lang}\n${code.replace(/\n+$/, '')}\n\`\`\``;
const oneLine = (s: string) =>
  s
    .replace(/\[\[([^\]|]+)(?:\|[^\]]+)?\]\]/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();

function bodySection(body: Body, heading: string): string[] {
  const out: string[] = [`${heading}`, ''];
  out.push(`- **Type:** ${body.type}`);
  out.push(`- **Learning outcome:** ${oneLine(body.learning_outcome)}`);
  out.push(`- **CSTA:** ${body.csta.join(', ')} · **About ${body.estimated_minutes} min**`);
  out.push(`- **Goal (as students see it):** ${oneLine(body.goal)}`, '');

  if (body.type === 'predict') {
    out.push('**Code students read:**', '', fence(body.starter_code), '', '**Answers:**', '');
    for (const p of body.prompts ?? []) {
      const answer = p.kind === 'mcq' ? p.options[p.answer] : p.answer;
      out.push(`- ${oneLine(p.question)} → **${oneLine(String(answer))}**. ${oneLine(p.explain)}`);
    }
    out.push('');
  } else if (body.type === 'investigate') {
    out.push('**Code students run:**', '', fence(body.starter_code), '', '**Answers:**', '');
    for (const q of body.questions ?? []) {
      const answer =
        q.kind === 'mcq'
          ? q.options[q.answer]
          : q.kind === 'number'
            ? String(q.answer)
            : q.accept.join(' / ');
      out.push(
        `- ${oneLine(q.question)} → **${oneLine(String(answer))}**${q.explain ? `. ${oneLine(q.explain)}` : ''}`,
      );
    }
    out.push('');
  } else {
    if (body.starter_code.trim()) out.push('**Starter code:**', '', fence(body.starter_code), '');
    for (const st of body.starters ?? [])
      out.push(
        `**Starter students can pick: ${st.title}** — ${oneLine(st.description)}`,
        '',
        fence(st.code),
        '',
      );
    if (body.duck)
      out.push(
        '**Talk to the Duck:** students explain each line in their own words first (not graded, not saved in files).',
        '',
      );
    out.push(
      '**Reference solution** (other correct answers also pass — the checks test behavior):',
      '',
      fence(solutionCode(body)),
      '',
    );
    for (const sample of body.sample_solutions)
      out.push(`**Another answer that passes: ${sample.name}**`, '', fence(sample.code), '');
    if (body.type === 'parsons' && body.parsons?.distractors.length) {
      out.push(
        `**Distractor lines (not used):** ${body.parsons.distractors.map((d) => `\`${d}\``).join(', ')}`,
        '',
      );
    }
  }

  if (body.inputs.length)
    out.push(`**Input values the quest provides:** ${body.inputs.map((v) => `\`${v}\``).join(', ')}`, '');
  if (body.common_mistakes.length) {
    out.push('**Common mistakes and the feedback students get:**', '');
    for (const m of body.common_mistakes) out.push(`- *${m.id}* — ${oneLine(m.feedback)}`);
    out.push('');
  }
  out.push('**Hints (free, in this order):**', '');
  body.hints.forEach((h, i) => {
    if (h.includes('```')) out.push(`${i + 1}. (code example)`, '', h.trim(), '');
    else out.push(`${i + 1}. ${oneLine(h)}`);
  });
  out.push('');
  return out;
}

function questSection(q: QuestFile): string[] {
  const tag = q.side_quest ? ' ⭐ side quest' : q.type === 'boss' ? ' 🐛 boss' : '';
  const out = [`### ${q.title}${tag}`, '', `\`${q.id}\``, ''];
  if (q.type === 'boss') {
    const boss = q as BossQuestFile;
    out.push(`**Boss:** ${boss.boss.name} (${boss.boss.bug}). ${oneLine(boss.goal)}`, '');
    boss.phases.forEach((phase: PhaseFile, i) =>
      out.push(...bodySection(phase, `#### Phase ${i + 1}: ${phase.title}`)),
    );
  } else {
    out.push(...bodySection(q as NormalQuestFile, '').slice(2));
  }
  return out;
}

export function buildAnswerKey(): string {
  const content = loadContent();
  if (content.problems.length) {
    reportProblems(content.problems);
    process.exit(1);
  }
  const lines: string[] = [
    '# Codeweald — Instructor Answer Key',
    '',
    '> **Generated by `npm run solutions` from `content/`. Do not edit by hand.**',
    '> Codeweald is a self-paced course with no teacher features in the app. This document lets',
    "> instructors prepare for students' questions. Reference solutions are *not* included in the",
    '> game itself. If this repository is public, students can read this file too.',
    '',
    'Each quest checks behavior, not exact text, so other correct programs also pass. The',
    '"common mistakes" are the targeted hints students see when the checker spots that mistake.',
    'See [curriculum-map.md](curriculum-map.md) for the full course outline and the',
    'misconceptions to watch for in each region.',
    '',
  ];
  const order = content.course?.data.regions.map((r) => r.id) ?? content.regions.map((r) => r.data.id);
  for (const regionId of order) {
    const region = content.regions.find((r) => r.data.id === regionId)?.data;
    if (!region) continue;
    lines.push(`## Region ${region.number} — ${region.name}`, '');
    lines.push(`**Concepts:** ${region.concepts.join('; ')}`, '');
    lines.push(`**Byte's analogy:** ${oneLine(region.concept_scene.analogy)}`, '');
    for (const id of [...region.quests, region.boss, ...region.side_quests]) {
      const q = content.quests.get(id)?.data;
      if (q) lines.push(...questSection(q));
    }
    lines.push('### Knowledge check', '');
    region.knowledge_check.items.forEach((item, i) => {
      if (item.kind === 'mcq') {
        lines.push(
          `${i + 1}. ${oneLine(item.question)} → **${item.options[item.answer]}**. ${oneLine(item.explain)}`,
        );
      } else {
        lines.push(
          `${i + 1}. ${oneLine(item.question)}`,
          '',
          fence(item.code),
          '',
          '   Answer:',
          '',
          fence(item.answer, 'text'),
          '',
          `   ${oneLine(item.explain)}`,
          '',
        );
      }
    });
    lines.push('');
  }
  return (
    lines
      .join('\n')
      .replace(/\n{3,}/g, '\n\n')
      .trimEnd() + '\n'
  );
}

const markdown = buildAnswerKey();
if (process.argv.includes('--check')) {
  const current = (() => {
    try {
      return readFileSync(OUT, 'utf8');
    } catch {
      return '';
    }
  })();
  if (current !== markdown) {
    console.error('✗ docs/solutions.md is out of date. Run `npm run solutions` and commit the result.');
    process.exit(1);
  }
  console.log('✓ docs/solutions.md is up to date');
} else {
  writeFileSync(OUT, markdown);
  console.log(`solutions: wrote docs/solutions.md (${markdown.split('\n').length} lines)`);
}
